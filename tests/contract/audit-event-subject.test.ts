interface AuditRow {
  audit_id: number;
  entity_type: string;
  entity_id: number;
  action: string;
  actor_advisor_id: number | null;
  actor_name_snapshot: string;
  origin: string;
  subject_student_id: number | null;
  subject_application_id: number | null;
  subject_fellowship_id: number | null;
}

interface SubjectRow {
  subject_type: string;
  subject_id: number;
  relationship: string;
  subject_name_snapshot: string | null;
}

async function readAudit(entityType: string, entityId: number): Promise<AuditRow[]> {
  const { rows } = await pool.query<AuditRow>(
    `SELECT audit_id::int AS audit_id, entity_type, entity_id, action, actor_advisor_id,
            actor_name_snapshot, origin, subject_student_id, subject_application_id,
            subject_fellowship_id
       FROM public.audit_event
      WHERE entity_type = $1 AND entity_id = $2
      ORDER BY audit_id`,
    [entityType, entityId]
  );
  return rows;
}

async function latestAuditId(entityType: string, entityId: number): Promise<number> {
  const { rows } = await pool.query<{ audit_id: number }>(
    `SELECT audit_id::int AS audit_id FROM public.audit_event
      WHERE entity_type = $1 AND entity_id = $2 ORDER BY audit_id DESC LIMIT 1`,
    [entityType, entityId]
  );
  if (!rows.length) throw new Error(`no audit event for ${entityType}#${entityId}`);
  return rows[0].audit_id;
}

async function readSubjects(auditId: number): Promise<SubjectRow[]> {
  const { rows } = await pool.query<SubjectRow>(
    `SELECT subject_type, subject_id, relationship, subject_name_snapshot
       FROM public.audit_event_subject
      WHERE audit_id = $1
      ORDER BY subject_type, subject_id, relationship`,
    [auditId]
  );
  return rows;
}

/** Canonical `type:id:relationship` set (sorted) for exact-set assertions. */
function assocSet(rows: Array<Pick<SubjectRow, "subject_type" | "subject_id" | "relationship">>): string[] {
  return rows.map((r) => `${r.subject_type}:${r.subject_id}:${r.relationship}`).sort();
}

function snapshotFor(rows: SubjectRow[], type: string, id: number, relationship: string): string | null {
  const row = rows.find(
    (r) => r.subject_type === type && r.subject_id === id && r.relationship === relationship
  );
  if (!row) throw new Error(`no subject row ${type}:${id}:${relationship}`);
  return row.subject_name_snapshot;
}

/** REAL authenticated TRUNCATE attempt (always rolled back). */
async function authenticatedTruncateCode(table: string): Promise<string | undefined> {
  const client: PoolClient = await pool.connect();
  try {
    await client.query("BEGIN");
    await client.query("SET LOCAL ROLE authenticated");
    const { rows } = await client.query<{ role: string }>("SELECT current_user AS role");
    if (rows[0]?.role !== "authenticated") {
      throw new Error(`could not assume the authenticated role (current_user=${rows[0]?.role})`);
    }
    try {
      await client.query(`TRUNCATE TABLE public.${table}`);
      return undefined;
    } catch (error) {
      return (error as { code?: string }).code;
    }
  } finally {
    await client.query("ROLLBACK").catch(() => undefined);
    client.release();
  }
}

/** REAL authenticated DDL/DML attempt as `authenticated` (always rolled back). */
async function authenticatedStatementCode(sql: string): Promise<string | undefined> {
  const client: PoolClient = await pool.connect();
  try {
    await client.query("BEGIN");
    await client.query("SET LOCAL ROLE authenticated");
    const { rows } = await client.query<{ role: string }>("SELECT current_user AS role");
    if (rows[0]?.role !== "authenticated") {
      throw new Error(`could not assume the authenticated role (current_user=${rows[0]?.role})`);
    }
    try {
      await client.query(sql);
      return undefined;
    } catch (error) {
      return (error as { code?: string }).code;
    }
  } finally {
    await client.query("ROLLBACK").catch(() => undefined);
    client.release();
  }
}

