/**
 * tests/contract/audit-event-subject.test.ts
 *
 * Contract coverage for the AI-DLC change `complete-immutable-history-context`
 * (forward-only migration ordered AFTER
 * `20261019000001_final_immutable_history_remediation.sql`).
 *
 * The suite proves the database behaviors the change requires (R4–R10):
 *
 *   - R4  An application student/fellowship re-link is ONE audit event with the
 *         application as `subject`, the old endpoints as `previous`, and the new
 *         endpoints as `current`; either endpoint's history resolves that same
 *         event exactly once (no duplicate activity rows).
 *   - R5  Scholarship History corrections use the effective fellowship
 *         IMMEDIATELY before the amendment as `previous` and the corrected
 *         fellowship as `current` (Goldwater -> Fulbright -> Marshall); a Void
 *         retains the immediately prior effective fellowship as `current` and
 *         creates no new fellowship; a later correction never reverts its
 *         previous to the base award.
 *   - R6  A new application-specific meeting captures student/current,
 *         application/subject, and application-time fellowship/current; a later
 *         amendment inherits application/fellowship context from the parent
 *         meeting's immutable creation event, so a subsequent application
 *         re-link does NOT change the amendment's frozen fellowship; General
 *         Advising has no fellowship association.
 *   - R7  The `security_invoker` `audit_activity` view exposes relationship-aware
 *         safe scalar snapshots and association-ID membership, returns ONE row
 *         per audit id, and filters on every associated subject id.
 *   - R8  Trusted baseline import is transaction-local and callable only by
 *         `service_role` / authorized DBA context; a spoofed transaction GUC in
 *         an untrusted session is not authority, and ordinary behavior returns
 *         after the baseline transaction commits.
 *   - R9  `audit_event_subject` is active-advisor SELECT-only (no product role
 *         can INSERT/UPDATE/DELETE/TRUNCATE), and public callers cannot execute
 *         the internal subject/audit helpers.
 *   - R10/R1/R1b/R2/R3 (isolated scratch replay): the upgrade backfill builds
 *         associations from immutable `audit_event` evidence only, repairs the
 *         faulty post-20261019 scholarship/void derived rows without modifying
 *         `audit_event`, leaves unproven legacy labels NULL, stays duplicate-free
 *         on reapply, and never fabricates history from mutable state.
 *
 * Design naming note: the relationship-aware view scalars asserted here are the
 * ones named in the authoritative design (`previous_student_name`,
 * `current_student_name`, `previous_fellowship_name`, `current_fellowship_name`,
 * `subject_application_name`).
 *
 * Service role is used strictly for synthetic fixture seeding and the admin
 * pre-bind; direct SQL (the loopback DB) is used as the persisted-state oracle.
 * Neither is asserted as an access grant.
 */
