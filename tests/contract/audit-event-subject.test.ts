/**
 * Minimal untyped PostgREST accessor. `audit_event_subject` and the baseline
 * RPC are owned by the new forward-only migration; the generated types are
 * regenerated by the migration writer, so this suite reads them through a
 * narrow untyped adapter (the same technique historical-audit-activity uses for
 * the activity view) and never depends on a type file it must not edit.
 */
interface UntypedResult {
  data: Array<Record<string, unknown>> | null;
  error: { code?: string; message?: string } | null;
}
interface UntypedQuery extends PromiseLike<UntypedResult> {
  select(columns?: string): UntypedQuery;
  eq(column: string, value: unknown): UntypedQuery;
  limit(count: number): UntypedQuery;
}
interface UntypedClient {
  from(table: string): { select(columns?: string): UntypedQuery };
}
function untyped(client: SupabaseClient): UntypedClient {
  return client as unknown as UntypedClient;
}
interface UntypedRpcClient {
  rpc(name: string): Promise<UntypedResult>;
}
function untypedRpc(client: SupabaseClient): UntypedRpcClient {
  return client as unknown as UntypedRpcClient;
}

interface Actor {
  userId: string;
  email: string;
  advisorName: string;
  client: SupabaseClient;
  advisorId: number;
}

async function insertAdvisor(advisorName: string, email: string, isActive = true): Promise<number> {
  const { data, error } = await service
    .from("advisor")
    .insert({ advisor_name: advisorName, email, is_active: isActive })
    .select("advisor_id")
    .single();
  if (error) throw new Error(`seed advisor ${advisorName}: ${error.message}`);
  return data.advisor_id as number;
}

/** ADMIN PRE-BINDING: the only legitimate way `auth_user_id` is ever written. */
async function bindAdvisor(advisorId: number, userId: string): Promise<void> {
  const { error } = await service
    .from("advisor")
    .update({ auth_user_id: userId })
    .eq("advisor_id", advisorId)
    .select("advisor_id");
  if (error) throw new Error(`admin pre-bind advisor ${advisorId}: ${error.message}`);
}

async function createBoundActor(label: string): Promise<Actor> {
  const tag = nextUnique(label);
  const email = syntheticEmail(tag);
  const advisorName = syntheticName(tag);
  const userId = await createAuthUser(service, email);
  const advisorId = await insertAdvisor(advisorName, email, true);
  await bindAdvisor(advisorId, userId);
  const client = freshClient();
  const signed = await signInWithPassword(client, email);
  if (signed !== userId) throw new Error(`${label} sign-in returned a different user`);
  return { userId, email, advisorName, client, advisorId };
}

/** Signed-in authenticated user with NO advisor row at all (RLS-filtered to zero). */
async function createNoAdvisorActor(label: string): Promise<Actor> {
  const tag = nextUnique(label);
  const email = syntheticEmail(tag);
  const userId = await createAuthUser(service, email);
  const client = freshClient();
  const signed = await signInWithPassword(client, email);
  if (signed !== userId) throw new Error(`${label} sign-in returned a different user`);
  return { userId, email, advisorName: "", client, advisorId: -1 };
}

