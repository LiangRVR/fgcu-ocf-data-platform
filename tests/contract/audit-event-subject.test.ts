describe("application re-link semantics (R4)", () => {
  it("records one event with the application subject and both old/new endpoints, retrievable once from either side", async () => {
    const studentA = await seedStudent("relink-student-a");
    const studentB = await seedStudent("relink-student-b");
    const fellowshipA = await seedFellowship("relink-fellowship-a");
    const fellowshipB = await seedFellowship("relink-fellowship-b");
    const applicationId = await seedApplicationFor(studentA, fellowshipA);

    const result = await updateApplicationViaWriter(staff, applicationId, {
      p_student_id: studentB,
      p_fellowship_id: fellowshipB,
    });
    expect(result.error, "application re-link writer").toBeNull();

    const events = await readAudit("application", applicationId);
    const updated = events.filter((e) => e.action === "updated");
    expect(updated, "exactly one updated event for the re-link").toHaveLength(1);
    const auditId = updated[0].audit_id;

    const subjects = await readSubjects(auditId);
    expect(assocSet(subjects), "application subject + old previous + new current").toEqual(
      [
        `application:${applicationId}:subject`,
        `student:${studentA}:previous`,
        `student:${studentB}:current`,
        `fellowship:${fellowshipA}:previous`,
        `fellowship:${fellowshipB}:current`,
      ].sort()
    );

    // Either endpoint's history retrieves that same event exactly once.
    for (const studentId of [studentA, studentB]) {
      const { rows } = await pool.query<{ n: number }>(
        `SELECT count(*)::int AS n
           FROM public.audit_activity
          WHERE audit_id = $1 AND student_subject_ids @> ARRAY[$2]::integer[]`,
        [auditId, studentId]
      );
      expect(rows[0].n, `student ${studentId} history resolves the re-link once`).toBe(1);
    }
    for (const fellowshipId of [fellowshipA, fellowshipB]) {
      const { rows } = await pool.query<{ n: number }>(
        `SELECT count(*)::int AS n
           FROM public.audit_activity
          WHERE audit_id = $1 AND fellowship_subject_ids @> ARRAY[$2]::integer[]`,
        [auditId, fellowshipId]
      );
      expect(rows[0].n, `fellowship ${fellowshipId} history resolves the re-link once`).toBe(1);
    }
  });
});

