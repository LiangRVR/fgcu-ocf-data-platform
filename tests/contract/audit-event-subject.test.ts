describe("scholarship correction chain and Void (R5)", () => {
  it("uses the immediately prior effective fellowship at every correction and retains it on Void", async () => {
    const studentId = await seedStudent("scholarship-chain-student");
    const goldwater = await seedFellowship("chain-goldwater");
    const fulbright = await seedFellowship("chain-fulbright");
    const marshall = await seedFellowship("chain-marshall");

    const { data: history, error: historyError } = await staff.client
      .from("scholarship_history")
      .insert({ student_id: studentId, fellowship_id: goldwater })
      .select("history_id")
      .single();
    expect(historyError, "scholarship_history base insert").toBeNull();
    const historyId = history!.history_id as number;

    const addAmendment = async (
      amendmentType: "Correction" | "Void",
      correctedFellowshipId?: number
    ): Promise<number> => {
      const { data, error } = await staff.client
        .from("scholarship_history_amendment")
        .insert({
          history_id: historyId,
          amendment_type: amendmentType,
          reason: "contract chain amendment",
          corrected_fellowship_id: correctedFellowshipId ?? null,
        })
        .select("amendment_id")
        .single();
      if (error) throw new Error(`scholarship amendment insert: ${error.message}`);
      return data!.amendment_id as number;
    };

    // Goldwater -> Fulbright.
    const correction1 = await addAmendment("Correction", fulbright);
    const correction1Subjects = await readSubjects(await latestAuditId("scholarship_history_amendment", correction1));
    expect(assocSet(correction1Subjects), "correction 1: base previous, corrected current").toEqual(
      [
        `student:${studentId}:current`,
        `fellowship:${goldwater}:previous`,
        `fellowship:${fulbright}:current`,
      ].sort()
    );
    // Newly generated events retain their event-time label snapshots (R3).
    expect(snapshotFor(correction1Subjects, "fellowship", goldwater, "previous")).toBe(
      await fellowshipName(goldwater)
    );
    expect(snapshotFor(correction1Subjects, "fellowship", fulbright, "current")).toBe(
      await fellowshipName(fulbright)
    );

    // Fulbright -> Marshall: previous must be Fulbright, never the base Goldwater.
    const correction2 = await addAmendment("Correction", marshall);
    const correction2Subjects = await readSubjects(await latestAuditId("scholarship_history_amendment", correction2));
    expect(assocSet(correction2Subjects), "correction 2: prior effective previous, corrected current").toEqual(
      [
        `student:${studentId}:current`,
        `fellowship:${fulbright}:previous`,
        `fellowship:${marshall}:current`,
      ].sort()
    );

    // Void retains the immediately prior effective fellowship (Marshall) as
    // current and creates no new fellowship. The proof is FIXTURE-SCOPED — no
    // global fellowship table total (which races concurrent suites): the Void
    // records NO corrected fellowship and derives EXACTLY the retained Marshall
    // context (student current + Marshall current only), with no additional
    // fellowship association rows.
    const voidId = await addAmendment("Void");

    const { rows: voidAmendment } = await pool.query<{
      amendment_type: string;
      corrected_fellowship_id: number | null;
    }>(
      `SELECT amendment_type, corrected_fellowship_id
         FROM public.scholarship_history_amendment WHERE amendment_id = $1`,
      [voidId]
    );
    expect(voidAmendment, "the Void amendment row exists").toHaveLength(1);
    expect(voidAmendment[0].amendment_type, "the event is a Void").toBe("Void");
    expect(
      voidAmendment[0].corrected_fellowship_id,
      "a Void records no corrected fellowship (creates no new fellowship)"
    ).toBeNull();

    const voidAuditId = await latestAuditId("scholarship_history_amendment", voidId);
    const voidSubjects = await readSubjects(voidAuditId);
    expect(assocSet(voidSubjects), "void: prior effective fellowship as current only").toEqual(
      [`student:${studentId}:current`, `fellowship:${marshall}:current`].sort()
    );
    // Fixture-scoped context count: exactly ONE fellowship association (the
    // retained Marshall); the Void invents no additional fellowship context.
    const { rows: voidFellowshipAssoc } = await pool.query<{ n: number }>(
      `SELECT count(*)::int AS n FROM public.audit_event_subject
        WHERE audit_id = $1 AND subject_type = 'fellowship'`,
      [voidAuditId]
    );
    expect(voidFellowshipAssoc[0].n, "the Void derives exactly the retained fellowship context").toBe(1);
  });
});

